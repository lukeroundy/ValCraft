        {
            int cl = p[9];
            return new Q { Req = BitConverter.ToUInt32(p, 0), Count = BitConverter.ToUInt16(p, 4), Dur = BitConverter.ToUInt16(p, 6), Quality = Math.Max(1, (int)p[8]),
