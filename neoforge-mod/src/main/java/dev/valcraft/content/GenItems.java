/**
 * 0.11.0: every Valheim item missing in Minecraft, registered from /valcraft_items.json (generated by tools/gen_content.py).
 * Stats are scaled to Valheim's tiers (0 Meadows .. 6 Ashlands): melee damage matches Valheim's damage / CombatScale so the
 * MC attack attribute is what Valheim monsters receive.
 */
public final class GenItems {
	private GenItems() {}
	public static final List<DeferredItem<? extends Item>> ALL = new ArrayList<>();
	public static final Map<String, List<DeferredItem<? extends Item>>> BY_TAB = new HashMap<>();
	static final Map<String, Holder<ArmorMaterial>> SETS = new HashMap<>();

	// tier tables: durability, mining speed, sword damage bonus, incorrect-for blocks
	static final int[] DUR = { 150, 280, 500, 900, 1500, 2000, 2600, 3200 };
	static final float[] SPEED = { 4f, 6.5f, 7f, 8f, 8.5f, 9f, 9.5f, 10f };
	static final float[] BONUS = { 0.5f, 2f, 5f, 8.5f, 12f, 16f, 20f, 24f };
	@SuppressWarnings("unchecked")
	static final TagKey<Block>[] INCORRECT = new TagKey[] { BlockTags.INCORRECT_FOR_STONE_TOOL, BlockTags.INCORRECT_FOR_IRON_TOOL, BlockTags.INCORRECT_FOR_IRON_TOOL,
		BlockTags.INCORRECT_FOR_DIAMOND_TOOL, BlockTags.INCORRECT_FOR_DIAMOND_TOOL, BlockTags.INCORRECT_FOR_NETHERITE_TOOL, BlockTags.INCORRECT_FOR_NETHERITE_TOOL, BlockTags.INCORRECT_FOR_NETHERITE_TOOL };
	static final Tier[] TIERS = new Tier[8];
	static { for (int i = 0; i < 8; i++) TIERS[i] = new SimpleTier(INCORRECT[i], DUR[i], SPEED[i], BONUS[i], 10 + i, () -> Ingredient.EMPTY); }

	/** kind -> {damage multiplier of a same-tier sword, attack speed modifier}. */
	static final Map<String, float[]> MELEE = Map.ofEntries(Map.entry("sword", new float[] { 1f, -2.4f }), Map.entry("greatsword", new float[] { 1.4f, -3.0f }),
		Map.entry("knife", new float[] { 0.65f, -1.6f }), Map.entry("mace", new float[] { 1.1f, -2.8f }), Map.entry("club", new float[] { 1f, -2.9f }),
		Map.entry("sledge", new float[] { 1.45f, -3.4f }), Map.entry("axe", new float[] { 1f, -3.0f }), Map.entry("battleaxe", new float[] { 1.35f, -3.2f }),
		Map.entry("pickaxe", new float[] { 0.7f, -2.8f }), Map.entry("hoe", new float[] { 0.3f, -1.5f }), Map.entry("spear", new float[] { 0.95f, -2.6f }),
		Map.entry("atgeir", new float[] { 1.05f, -3.0f }), Map.entry("fist", new float[] { 0.8f, -1.4f }), Map.entry("staff", new float[] { 0.35f, -2.4f }));

	static ItemAttributeModifiers melee(int tier, String kind) {
		float[] k = MELEE.get(kind);
		float dmg = (4f + BONUS[tier]) * k[0]; // total damage incl. the player's base 1
		return ItemAttributeModifiers.builder()
			.add(Attributes.ATTACK_DAMAGE, new AttributeModifier(Item.BASE_ATTACK_DAMAGE_ID, dmg - 1f, AttributeModifier.Operation.ADD_VALUE), EquipmentSlotGroup.MAINHAND)
			.add(Attributes.ATTACK_SPEED, new AttributeModifier(Item.BASE_ATTACK_SPEED_ID, k[1], AttributeModifier.Operation.ADD_VALUE), EquipmentSlotGroup.MAINHAND).build();
	}

	static void init() {
		JsonObject root;
		try (var in = GenItems.class.getResourceAsStream("/valcraft_items.json")) {
			if (in == null) { ValCraft.LOG.error("[content] valcraft_items.json missing"); return; }
			root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
		} catch (Exception e) { ValCraft.LOG.error("[content] cannot read valcraft_items.json", e); return; }
		for (var se : root.getAsJsonArray("sets")) {
			var s = se.getAsJsonObject(); String name = s.get("name").getAsString(); var d = s.getAsJsonArray("def");
			int[] def = { d.get(0).getAsInt(), d.get(1).getAsInt(), d.get(2).getAsInt(), d.get(3).getAsInt() };
			float tough = s.get("tough").getAsFloat(); int ench = s.get("ench").getAsInt();
			SETS.put(name, ModContent.ARMOR.register(name, () -> {
				var m = new EnumMap<ArmorItem.Type, Integer>(ArmorItem.Type.class);
				m.put(ArmorItem.Type.BOOTS, def[0]); m.put(ArmorItem.Type.LEGGINGS, def[1]); m.put(ArmorItem.Type.CHESTPLATE, def[2]); m.put(ArmorItem.Type.HELMET, def[3]); m.put(ArmorItem.Type.BODY, def[2]);
				return new ArmorMaterial(m, ench, tough > 1.5f ? SoundEvents.ARMOR_EQUIP_NETHERITE : name.matches("rag|leather|troll|wolf|fenris|padded|eitr_weave|embla|ask|cloth") ? SoundEvents.ARMOR_EQUIP_LEATHER : SoundEvents.ARMOR_EQUIP_IRON,
					() -> Ingredient.EMPTY, List.of(new ArmorMaterial.Layer(ResourceLocation.fromNamespaceAndPath(ValCraft.MOD_ID, name))), tough, tough > 2.5f ? 0.1f : 0f);
			}));
			durMul.put(name, s.get("dur").getAsInt());
		}
		for (var ie : root.getAsJsonArray("items")) {
			var o = ie.getAsJsonObject(); String id = o.get("id").getAsString(), kind = o.get("kind").getAsString();
			int tier = Math.max(0, Math.min(7, o.get("tier").getAsInt()));
			String set = o.has("set") ? o.get("set").getAsString() : null;
			float[] food = o.has("food") ? new float[] { o.getAsJsonArray("food").get(0).getAsFloat(), o.getAsJsonArray("food").get(1).getAsFloat() } : null;
			DeferredItem<? extends Item> di = ModContent.ITEMS.register(id, () -> make(id, kind, tier, set, food));
			ALL.add(di); BY_TAB.computeIfAbsent(tab(kind, food != null), k -> new ArrayList<>()).add(di);
		}
		ValCraft.LOG.info("[content] {} Valheim items, {} armor sets", ALL.size(), SETS.size());
	}
	static final Map<String, Integer> durMul = new HashMap<>();

	static String tab(String kind, boolean food) {
		if (food) return "food";
		return switch (kind) {
			case "sword", "greatsword", "knife", "mace", "club", "sledge", "battleaxe", "spear", "atgeir", "fist", "staff", "bow", "crossbow", "arrow", "shield",
				"helmet", "chestplate", "leggings", "boots", "helmet_misc", "cape" -> "combat";
			case "axe", "pickaxe", "hoe" -> "tools";
			default -> "ingredients";
		};
	}

	static Item make(String id, String kind, int tier, String set, float[] food) {
		var p = new Item.Properties();
		switch (kind) {
			case "helmet", "chestplate", "leggings", "boots", "helmet_misc" -> {
				var t = switch (kind) { case "chestplate" -> ArmorItem.Type.CHESTPLATE; case "leggings" -> ArmorItem.Type.LEGGINGS; case "boots" -> ArmorItem.Type.BOOTS; default -> ArmorItem.Type.HELMET; };
				return new ArmorItem(SETS.get(set), t, p.durability(t.getDurability(durMul.getOrDefault(set, 10))));
			}
			case "cape" -> { return new Item(p.stacksTo(1)); }
			case "axe" -> { return new AxeItem(TIERS[tier], p.attributes(melee(tier, kind))); }
			case "pickaxe" -> { return new PickaxeItem(TIERS[tier], p.attributes(melee(tier, kind))); }
			case "hoe" -> { return new HoeItem(TIERS[tier], p.attributes(melee(tier, kind))); }
			case "sword", "greatsword", "knife", "mace", "club", "sledge", "battleaxe", "spear", "atgeir", "fist", "staff" -> { return new SwordItem(TIERS[tier], p.attributes(melee(tier, kind))); }
			case "bow" -> { return new BowItem(p.durability(DUR[tier] / 2)); }
			case "crossbow" -> { return new CrossbowItem(p.durability(DUR[tier] / 2)); }
			case "arrow" -> { return new ArrowItem(p); }
			case "shield" -> { return new ShieldItem(p.durability(DUR[tier] / 2 + 100)); }
			default -> {}
		}
		if (food != null) {
			float hp = food[0], st = food[1];
			var fb = new FoodProperties.Builder();
			if (kind.equals("mead")) {
				fb.nutrition(1).saturationModifier(0.1f).alwaysEdible();
				var eff = id.contains("healing") ? new MobEffectInstance(MobEffects.HEAL, 1, id.contains("major") ? 2 : id.contains("medium") ? 1 : 0)
					: id.contains("stamina") || id.contains("hasty") || id.contains("lightfoot") ? new MobEffectInstance(MobEffects.MOVEMENT_SPEED, 1200, id.contains("medium") || id.contains("hasty") ? 1 : 0)
					: id.contains("fire") ? new MobEffectInstance(MobEffects.FIRE_RESISTANCE, 6000) : id.contains("frost") ? new MobEffectInstance(MobEffects.DAMAGE_RESISTANCE, 6000)
					: id.contains("poison") ? new MobEffectInstance(MobEffects.REGENERATION, 400) : id.contains("eitr") ? new MobEffectInstance(MobEffects.NIGHT_VISION, 3600)
					: id.contains("strength") || id.contains("bzerker") ? new MobEffectInstance(MobEffects.DAMAGE_BOOST, 1200) : id.contains("swimmer") ? new MobEffectInstance(MobEffects.WATER_BREATHING, 3600)
					: new MobEffectInstance(MobEffects.LUCK, 3600);
				fb.effect(() -> eff, 1f);
				return new Item(p.stacksTo(10).food(fb.build()));
			}
			int nut = Math.max(1, Math.min(20, Math.round((hp + st) / 10f)));
			fb.nutrition(hp + st <= 2 ? 2 : nut).saturationModifier(hp + st <= 2 ? 0.3f : 0.3f + 0.7f * hp / Math.max(1f, hp + st));
			if (hp + st <= 2 && !kind.equals("berry")) fb.effect(() -> new MobEffectInstance(MobEffects.HUNGER, 300), 0.3f);
			if (kind.equals("bowl")) { fb.usingConvertsTo(Items.BOWL); p.stacksTo(16); }
			return new Item(p.food(fb.build()));
		}
		return new Item(p);
	}
}
